from typing import Protocol


class TicketRepository(Protocol):
    """Persistence port. Services only know this interface (Supabase or in-memory)."""

    def create(self, data: dict) -> dict: ...
    def get(self, ticket_id: int) -> dict | None: ...
    def list(self, category: str | None, status: str | None, limit: int, offset: int) -> list[dict]: ...
    def update(self, ticket_id: int, fields: dict) -> dict | None: ...
